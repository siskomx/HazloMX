import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {transformWithOxc} from "vite";

const {code}=await transformWithOxc(await readFile(new URL("../src/design.ts",import.meta.url),"utf8"),"design.ts");
const {agentPrompt,savedConversation,CHAT_HISTORY_BYTES}=await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const history=Array.from({length:12},(_,i)=>({role:i%2?"assistant":"user",content:i%2?`Explicación ${i}: ${"medida confirmada á🛠️ ".repeat(90)}`:`Restricción del usuario ${i}: conserva esta medida.`}));
const original=structuredClone(history), current={current_job:{id:"verified-result",phase:"completed"},drawing_source:{selection:"selected-drawing",sha256:"a".repeat(64)}};
const request="Lee el resultado verificado, explica sus límites y no prepares otro cambio.";
const encoded=agentPrompt(request,history,current), prompt=JSON.parse(encoded);
assert(Buffer.byteLength(encoded)<=8192);
assert(prompt.omitted_conversation_turns>0&&prompt.omitted_conversation_turns<history.length);
assert.equal(prompt.recovered_conversation.length,history.length-prompt.omitted_conversation_turns);
assert.deepEqual(prompt.recovered_conversation.filter(t=>t.role==="user"),history.filter(t=>t.role==="user"),"Verbose explanations displaced user constraints");
assert.deepEqual(prompt.recovered_conversation,history.filter(turn=>prompt.recovered_conversation.some(retained=>retained.content===turn.content)),"Retained messages changed order or content");
assert.deepEqual(prompt.desktop_context,current);
assert.equal(prompt.user_request,request);
assert.match(prompt.instruction,/No supongas sus datos/);
assert.match(prompt.instruction,/Para continuar con el mismo documento/);
assert.match(prompt.instruction,/idea; acordar el programa/);
assert.match(prompt.instruction,/inspect_open_cad_documents/);
assert.match(prompt.instruction,/no lo sustituyas por una copia guardada/);
assert.match(prompt.instruction,/propose_open_cad_change/);
assert.match(prompt.instruction,/No repitas una escritura incierta/);
assert.match(prompt.instruction,/pendiente, fallida o cancelada no sustituye ese resultado/);
assert.deepEqual(history,original,"Composing a bounded request changed visible/saved history");
const planning=JSON.parse(agentPrompt("Ayúdame a elegir por dónde empezar.",history,{program:"planning",program_selection_required:true}));
assert.match(planning.instruction,/una sola pregunta breve por turno/);
assert.match(planning.instruction,/como máximo dos opciones relevantes/);
assert.match(planning.instruction,/no afirmes haber cambiado la selección/);
assert(!planning.instruction.includes("propose_open_cad_change"),"Choosing software included unrelated editing instructions");
assert.deepEqual(planning.recovered_conversation.filter(t=>t.role==="user"),history.filter(t=>t.role==="user"));
const hugeReply=JSON.parse(agentPrompt(request,[{role:"assistant",content:"á".repeat(10000)}],current));
assert.equal(hugeReply.omitted_conversation_turns,1);
assert.deepEqual(hugeReply.recovered_conversation,[]);
const manyRequests=JSON.parse(agentPrompt(request,Array.from({length:12},(_,i)=>({role:"user",content:`${i}: ${"á".repeat(1000)}`})),current));
assert(manyRequests.omitted_conversation_turns>0);
assert(manyRequests.recovered_conversation.at(-1).content.startsWith("11:"),"The newest user constraint was dropped first");
assert.throws(()=>agentPrompt("á".repeat(5000),history,current),/8 KiB/);
assert.throws(()=>agentPrompt(request,history,{value:"á".repeat(5000)}),/8 KiB/);
const saved=JSON.stringify({version:1,turns:history,answeredChat:"last-chat"});
assert(Buffer.byteLength(saved)>8192);
assert.equal(savedConversation(saved),null,"Legacy parser bound changed");
assert.deepEqual(savedConversation(saved,CHAT_HISTORY_BYTES).turns,history);
assert.equal(savedConversation(JSON.stringify({version:1,turns:Array(129).fill(history[0])}),CHAT_HISTORY_BYTES),null);
assert.equal(savedConversation(JSON.stringify({version:1,turns:[{role:"user",content:"x".repeat(CHAT_HISTORY_BYTES)}]}),CHAT_HISTORY_BYTES),null);
console.log("PASS: UTF-8 request bound, user constraints before verbose replies, complete ordered messages, current request/document/job preserved, explicit omitted-history marker, unchanged full history and separate bounded chat storage");
